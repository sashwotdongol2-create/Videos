"""Writes out/cues.json for the real-sound mixer from the word timings (src/bell_words.json) and the section table
(SHOT_FRAMES.txt, 30 fps). The film is ONE continuous camera move in 4 sections (joined inside black doorways);
the Blender section files were not written yet when this ran, so every sync point is computed from a word's
start/end, a section boundary, or the beat list in audio/SOUND_BRIEF.md (which was written from AGENT_BRIEF.md).
Re-run after any re-timing of the voice. Run: <py> audio/make_cues.py   (from the project root)."""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FPS = 30
W = json.load(open(os.path.join(ROOT, "src/bell_words.json"), encoding="utf-8"))
SH = {}
for ln in open(os.path.join(ROOT, "SHOT_FRAMES.txt"), encoding="utf-8"):
    p = ln.split()
    if len(p) >= 3 and p[0].isdigit():
        SH[int(p[0])] = (int(p[1]), int(p[2]))
TOTAL = SH[max(SH)][1]


def ws(i): return W[i]["s"]
def we(i): return W[i]["e"]
def sec_t(i): return SH[i][0] / FPS


ev = []
def add(t, kind, id_, weight=1.0, pan=0.0, **kw):
    e = {"f": round(t * FPS, 3), "kind": kind, "id": id_, "weight": weight, "pan": pan}
    e.update(kw)
    ev.append(e)


# ---- 1. ruined Berlin street + garden (frames 0-250) ---------------------------------------------------------------
# Soviet soldiers fire: two volleys of two rifles each, distant, early in the street (~0.5 and ~2.6 s)
add(ws(2) + 0.08, "rifle", "street:volley:0:a", pan=-0.3)        # on "Soviet" (word 2)
add(ws(2) + 0.17, "rifle", "street:volley:0:b", pan=0.25, weight=0.8)
add(ws(10) + 0.35, "rifle", "street:volley:1:a", pan=0.3, weight=0.9)   # inside the long tail of "Berlin," (word 10)
add(ws(10) + 0.46, "rifle", "street:volley:1:b", pan=-0.2, weight=0.7)
# garden: gravel steps toward the bunker entrance, the steel door opens, we pass through, it closes on the black join
add(we(17) + 0.05, "steps", "garden:gravel:0", pan=0.1)          # after "out." (word 17)
add(ws(24) - 0.05, "door", "garden:door:open:0")                # "last" (word 24): the door swings open
add(we(25) + 0.01, "door", "garden:door:close:0", weight=1.2)   # after "hours?" (word 25), in the black join (8.11 s)

# ---- 2. bunker stairs, wedding room, breakfast (frames 250-662) ----------------------------------------------------
add(sec_t(2) + 0.1, "steps", "bunker:stairs:0")                  # out of the black onto the concrete stairs
add(we(32) + 0.02, "thud", "bunker:thud:0", weight=0.6, pan=-0.2)   # after "bunker," (word 32): distant shelling
add(we(39) + 0.03, "thud", "bunker:thud:1", weight=0.8, pan=0.25)   # after "Braun." (word 39), wedding room
for k, t in enumerate((ws(43), ws(45) + 0.05, we(45) + 0.06, ws(49) + 0.02)):   # breakfast: plates and cutlery
    add(t, "clink", f"breakfast:clink:{k}", weight=0.8 if k else 1.0, pan=(-0.15, 0.2, 0.05, -0.2)[k])
add(ws(62) - 0.02, "scrape", "breakfast:chair:0", pan=-0.2)      # "slipped" (word 62): chairs pushed back
add(ws(63) + 0.05, "scrape", "breakfast:chair:1", pan=0.25, weight=0.8)
add(we(63) + 0.15, "steps", "breakfast:leave:0", pan=0.1)        # "away early." (words 63-64): staff walk out

# ---- 3. radio room (frames 662-1167) ----------------------------------------------------------------------------------
add(ws(68) - 0.03, "impact", "radio:shell:0", weight=1.0)        # "Soviet guns could be heard" (words 68-72)
add(ws(68) + 0.25, "debris", "radio:dust:0", pan=0.1)            # dust trickles from the ceiling
add(ws(68) + 0.45, "creak", "radio:lamp:0", pan=-0.1)            # the hanging lamp sways
add(we(81) + 0.02, "thud", "radio:thud:2", weight=0.8, pan=0.3)  # after "over." (word 81)

# ---- 4. hallway handshakes, corridor, steel door, study, the shot (frames 1167-1588) ---------------------------------
for k, t in enumerate((ws(116), ws(120) + 0.05, ws(121) + 0.1)):  # "shook hands ... staff, thanked them"
    add(t, "cloth", f"hall:handshake:{k}", pan=(-0.2, 0.1, 0.25)[k])
add(ws(124) - 0.02, "steps", "hall:walk:0")                      # "walked into his private rooms"
add(we(131) + 0.03, "door", "hall:door:close:1", weight=1.0)     # after "wife." (word 131): the steel door shuts
add(ws(144) - 0.1, "dog", "study:dog:0", pan=-0.25)              # "his dog," (words 144-145): asleep, soft breath
add(ws(150), "gunshot", "study:gunshot:0")                      # "gunshot" (word 150): off-screen, through the door

ev.sort(key=lambda e: e["f"])
acts = {"berlin": [0, SH[2][0]], "wedding": [SH[2][0], SH[3][0]], "radio": [SH[3][0], SH[4][0]],
        "farewell": [SH[4][0], TOTAL]}
out = {"_doc": "Generated by audio/make_cues.py from src/bell_words.json + SHOT_FRAMES.txt (30 fps).",
       "fps": FPS, "total": TOTAL, "acts": {k: {"from": a, "dur": b - a} for k, (a, b) in acts.items()},
       "events": ev}
os.makedirs(os.path.join(ROOT, "out"), exist_ok=True)
json.dump(out, open(os.path.join(ROOT, "out/cues.json"), "w"), indent=1)
for e in ev:
    print(f"{e['f'] / FPS:6.2f}  {e['kind']:8} {e['id']}")
print(len(ev), "events")
